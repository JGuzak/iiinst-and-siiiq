local loader = require("tests.helpers.load_iiiano")

describe("random velocity", function()
    it("selects a range with either pair of modifiers and preserves static velocity", function()
        local env, state = loader.new_context()
        assert.are.equal(0, state.grid_state[15][3])
        assert.are.equal(15, state.grid_state[16][3])
        env.event_grid(14,3,1)
        assert.are.equal(15, state.grid_state[14][3])
        assert.are.equal(15, state.grid_state[14][4])
        env.event_grid(15,3,1); env.event_grid(14,8,1); env.event_grid(15,3,0)
        assert.are.equal(1, state.grid_state[15][3])
        assert.are.equal(1, state.grid_state[15][4])
        env.event_grid(16,4,1); env.event_grid(14,5,1); env.event_grid(16,4,0)
        assert.are.equal(13, state.grid_state[16][3])
        state.set_random_queue({52})
        env.event_grid(1,8,1); env.event_grid(1,8,0)
        assert.are.equal(env.get_v_from_vi(2), state.random_ranges[1][1])
        assert.are.equal(env.get_v_from_vi(14), state.random_ranges[1][2])
        assert.are.equal(52, state.midi_calls[1].velocity)
        env.event_grid(14,4,1)
        assert.are.equal(8, state.grid_state[14][3])
        env.event_grid(1,8,1); env.event_grid(1,8,0)
        assert.are.equal(104, state.midi_calls[3].velocity)
    end)

    it("handles equal and inverted endpoints and releases held modifiers", function()
        local env, state = loader.new_context()
        env.event_grid(14,4,1)
        env.event_grid(15,4,1); env.event_grid(16,5,1); env.event_grid(15,4,0)
        env.event_grid(16,3,1); env.event_grid(13,8,1); env.event_grid(16,3,0)
        assert.are.equal(15, state.grid_state[15][4])
        assert.are.equal(0, state.grid_state[16][4])
        env.event_grid(1,8,1); env.event_grid(1,8,0)
        assert.are.equal(10, state.random_ranges[1][1])
        assert.are.equal(127, state.random_ranges[1][2])
        env.event_grid(16,3,1); env.event_grid(16,5,1); env.event_grid(16,3,0)
        env.event_grid(1,8,1); env.event_grid(1,8,0)
        assert.are.equal(127, state.random_ranges[2][1])
        assert.are.equal(127, state.random_ranges[2][2])
        env.event_grid(13,8,1) -- no modifier: range stays fixed
        env.event_grid(1,8,1); env.event_grid(1,8,0)
        assert.are.equal(127, state.random_ranges[3][1])
        assert.are.equal(127, state.random_ranges[3][2])
    end)
    it("blinks both mode buttons only in random mode", function()
        local env, state = loader.new_context()
        assert.are.equal(8, state.grid_state[14][3])
        assert.are.equal(8, state.grid_state[14][4])
        env.event_grid(14,3,1)
        state.set_time(300); env.render_selected_vel()
        assert.are.equal(2, state.grid_state[14][3])
        assert.are.equal(2, state.grid_state[14][4])
        state.set_time(0); env.render_selected_vel()
        assert.are.equal(15, state.grid_state[14][3])
        assert.are.equal(15, state.grid_state[14][4])
        env.event_grid(14,4,1)
        assert.are.equal(8, state.grid_state[14][3])
        assert.are.equal(8, state.grid_state[14][4])
    end)

    it("updates both endpoint LEDs when selecting while static", function()
        local env, state = loader.new_context()
        env.event_grid(15,3,1); env.event_grid(15,8,1); env.event_grid(15,3,0)
        assert.are.equal(2, state.grid_state[15][3])
        assert.are.equal(2, state.grid_state[15][4])
        env.event_grid(16,4,1); env.event_grid(14,6,1); env.event_grid(16,4,0)
        assert.are.equal(9, state.grid_state[16][3])
        assert.are.equal(9, state.grid_state[16][4])
        env.event_grid(1,8,1)
        assert.are.equal(104, state.midi_calls[1].velocity)
    end)
    it("pulses held endpoint pairs and restores selected brightness on both grids", function()
        for _,height in ipairs({8,16}) do
            for _,random_mode in ipairs({false,true}) do
                local env,state=loader.new_context({grid_size_y=height})
                local mode_x,mode_y,min_x,max_x,row1,row2,pad_x,pad_y
                if height==8 then mode_x,mode_y,min_x,max_x,row1,row2,pad_x,pad_y=14,3,15,16,3,4,14,8
                else mode_x,mode_y,min_x,max_x,row1,row2,pad_x,pad_y=3,2,4,5,2,3,3,7 end
                if random_mode then env.event_grid(mode_x,mode_y,1); env.event_grid(mode_x,mode_y,0) end
                env.event_grid(min_x,row1,1)
                state.set_time(0); env.render_selected_vel()
                assert.are.equal(2,state.grid_state[min_x][row1]); assert.are.equal(2,state.grid_state[min_x][row2])
                state.set_time(500); env.render_selected_vel()
                assert.are.equal(9,state.grid_state[min_x][row1]); assert.are.equal(9,state.grid_state[min_x][row2])
                state.set_time(1000); env.render_selected_vel()
                assert.are.equal(15,state.grid_state[min_x][row1]); assert.are.equal(15,state.grid_state[min_x][row2])
                env.event_grid(pad_x,pad_y,1); env.event_grid(pad_x,pad_y,0)
                env.event_grid(min_x,row1,0)
                assert.are.equal(1,state.grid_state[min_x][row1]); assert.are.equal(1,state.grid_state[min_x][row2])
                env.event_grid(max_x,row2,1)
                state.set_time(1500); env.render_selected_vel()
                assert.are.equal(9,state.grid_state[max_x][row1]); assert.are.equal(9,state.grid_state[max_x][row2])
                assert.are.equal(1,state.grid_state[min_x][row1])
                env.event_grid(max_x,row2,0)
                assert.are.equal(15,state.grid_state[max_x][row1]); assert.are.equal(15,state.grid_state[max_x][row2])
            end
        end
    end)

    it("keeps a pair pulsing until both of its held buttons are released",function()
        local env,state=loader.new_context()
        env.event_grid(15,3,1); env.event_grid(15,4,1)
        env.event_grid(15,3,0)
        state.set_time(1000); env.render_selected_vel()
        assert.are.equal(15,state.grid_state[15][3]); assert.are.equal(15,state.grid_state[15][4])
        env.event_grid(15,4,0)
        assert.are.equal(0,state.grid_state[15][3]); assert.are.equal(0,state.grid_state[15][4])
    end)
end)
