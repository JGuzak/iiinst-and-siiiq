local loader=require("tests.helpers.load_iiiano")

describe("retuning held notes",function()
    it("retunes held notes on a root change, preserving velocity and original channel",function()
        local env,state=loader.new_context()
        env.event_grid(14,1,1); env.event_grid(16,8,1); env.event_grid(16,8,0)
        env.event_grid(1,8,1); env.event_grid(3,8,1)
        env.event_grid(15,1,1); env.event_grid(14,5,1); env.event_grid(14,5,0) -- channel 2
        state.clear_logs()
        env.event_grid(14,1,1); env.event_grid(15,5,1) -- D root
        assert.are.equal(4,#state.midi_calls)
        assert.are.equal("note_off",state.midi_calls[1].type)
        assert.are.equal("note_off",state.midi_calls[2].type)
        assert.are.equal("note_on",state.midi_calls[3].type)
        assert.are.equal("note_on",state.midi_calls[4].type)
        for _,msg in ipairs(state.midi_calls) do assert.are.equal(1,msg.channel) end
        assert.are.equal(104,state.midi_calls[3].velocity)
        env.event_grid(15,5,0)
        state.clear_logs()
        env.event_grid(1,8,0); env.event_grid(3,8,0)
        assert.are.equal(26,state.midi_calls[1].note)
        assert.are.equal(30,state.midi_calls[2].note)
        assert.are.equal(1,state.midi_calls[1].channel)
    end)

    it("retunes latched notes on Grid Zero and releases the new pitch",function()
        local env,state=loader.new_context({grid_size_y=16})
        env.event_grid(10,7,1); env.event_grid(10,7,0) -- in-key mode
        env.event_grid(3,1,1) -- note hold toggle
        env.event_grid(1,16,1); env.event_grid(1,16,0)
        state.clear_logs()
        env.event_grid(9,4,1); env.event_grid(9,4,0) -- D root
        assert.are.equal(24,state.midi_calls[1].note)
        assert.are.equal("note_off",state.midi_calls[1].type)
        assert.are.equal(26,state.midi_calls[2].note)
        assert.are.equal("note_on",state.midi_calls[2].type)
        state.clear_logs(); env.event_grid(3,1,1)
        assert.are.equal(26,state.midi_calls[1].note)
        assert.are.equal("note_off",state.midi_calls[1].type)
    end)

    it("does not retune when the same root is reselected or in chromatic mode",function()
        local env,state=loader.new_context({grid_size_y=16})
        env.event_grid(1,16,1); state.clear_logs()
        env.event_grid(7,4,1); env.event_grid(7,4,0)
        assert.are.equal(0,#state.midi_calls)
        env.event_grid(9,4,1); env.event_grid(9,4,0)
        assert.are.equal(0,#state.midi_calls)
        env.event_grid(1,16,0)
        assert.are.equal(24,state.midi_calls[1].note)
    end)
    it("retunes only changed scale degrees and preserves velocity",function()
        local env,state=loader.new_context({grid_size_y=16})
        env.event_grid(10,7,1); env.event_grid(10,7,0)
        env.event_grid(1,16,1); env.event_grid(3,16,1) -- C and E
        state.clear_logs()
        env.event_grid(8,2,1); env.event_grid(8,2,0) -- C minor
        assert.are.equal(2,#state.midi_calls)
        assert.are.equal("note_off",state.midi_calls[1].type)
        assert.are.equal(28,state.midi_calls[1].note)
        assert.are.equal("note_on",state.midi_calls[2].type)
        assert.are.equal(27,state.midi_calls[2].note)
        assert.are.equal(104,state.midi_calls[2].velocity)
        state.clear_logs()
        env.event_grid(8,2,1); env.event_grid(8,2,0)
        assert.are.equal(0,#state.midi_calls)
        env.event_grid(3,16,0)
        assert.are.equal(27,state.midi_calls[1].note)
    end)

    it("keeps pitches unchanged and does not retrigger on a chromatic scale change",function()
        local env,state=loader.new_context({grid_size_y=16})
        env.event_grid(5,16,1); state.clear_logs()
        env.event_grid(8,2,1); env.event_grid(8,2,0)
        assert.are.equal(0,#state.midi_calls)
        env.event_grid(5,16,0)
        assert.are.equal(28,state.midi_calls[1].note)
    end)
    it("keeps out-of-range keys silent and handles held notes crossing the MIDI limit",function()
        local env,state=loader.new_context({grid_size_y=16})
        env.event_grid(10,7,1); env.event_grid(10,7,0) -- in-key
        env.event_grid(7,7,1); env.event_grid(7,7,0) -- octave rows
        assert.are.equal(0,state.grid_state[16][9])
        state.clear_logs(); env.event_grid(16,9,1); env.event_grid(16,9,0)
        assert.are.equal(0,#state.midi_calls)
        env.event_grid(10,9,1)
        assert.are.equal(124,state.midi_calls[1].note)
        state.clear_logs()
        env.event_grid(7,5,1); env.event_grid(7,5,0) -- E root: above MIDI range
        assert.are.equal(1,#state.midi_calls)
        assert.are.equal("note_off",state.midi_calls[1].type)
        assert.are.equal(124,state.midi_calls[1].note)
        state.clear_logs()
        env.event_grid(7,4,1); env.event_grid(7,4,0) -- back to C
        assert.are.equal(1,#state.midi_calls)
        assert.are.equal("note_on",state.midi_calls[1].type)
        assert.are.equal(124,state.midi_calls[1].note)
        env.event_grid(10,9,0)
        assert.are.equal("note_off",state.midi_calls[2].type)
    end)
end)
